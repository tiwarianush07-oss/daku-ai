"""
DAKU Reflection Engine Module
Phase 6: Adaptive Multi-Pass Reasoning & Safe Self-Learning

Provides:
- ReflectionEngine: Analyzes failed tool executions, compares expected vs actual system states,
  diagnoses failure causes, proposes safe alternative strategies, and prevents repeated failures.
- Never directly executes dangerous actions; outputs structured, safe strategy proposals.
"""

from dataclasses import dataclass, field
import logging
from typing import Any, Dict, List, Optional, Tuple

from tools.base import ToolResult

logger = logging.getLogger("daku.reflection")


@dataclass
class ReflectionResult:
    """Structured proposal generated by reflection analysis."""
    failure_reason: str
    root_cause: str
    expected_state: str
    actual_state: str
    suggested_action: Optional[str] = None
    suggested_tool: Optional[str] = None
    suggested_args: Optional[Dict[str, Any]] = None
    should_retry: bool = False
    explanation: str = ""


class ReflectionEngine:
    """
    Analyzes failed actions, contrasts expected vs real-world states,
    identifies faulty assumptions, and recommends safe alternative strategies.
    Strictly follows DAKU safety constraints:
    - Never executes actions directly.
    - Never suggests blocked or dangerous operations.
    - Recommends alternatives (e.g. Edge if Chrome fails, native fallback if MCP fails).
    """

    def __init__(self, learning_engine: Optional[Any] = None):
        self.learning_engine = learning_engine

    def reflect_on_failure(
        self,
        tool_name: str,
        args: Dict[str, Any],
        tool_result: ToolResult,
        expected: Optional[str] = None,
        context: Optional[Dict[str, Any]] = None,
        failed_history: Optional[List[Tuple[str, Dict[str, Any]]]] = None,
    ) -> ReflectionResult:
        """
        Reflects on why a tool execution or verification failed.
        Returns a ReflectionResult with diagnosis and proposed alternative strategy.
        """
        err_msg = (tool_result.error or tool_result.message or "Execution unverified").strip()
        err_lower = err_msg.lower()
        args_dict = args or {}
        action_name = args_dict.get("action") or args_dict.get("query") or tool_name
        history = failed_history or []

        logger.info(f"REFLECTION initiated for tool '{tool_name}' [Error: {err_msg}]")

        # 1. Application Launch Failure (e.g. Chrome not installed / executable missing)
        if tool_name == "application_tool" and args_dict.get("action") == "launch":
            app = str(args_dict.get("app_name", "")).lower()
            expected_state = f"{app} running as verified process"
            actual_state = f"{app} not running ({err_msg})"

            if "chrome" in app:
                # Check if we already tried edge
                already_tried_edge = any(
                    h[0] == "application_tool" and h[1].get("app_name") == "edge"
                    for h in history
                )
                if not already_tried_edge:
                    explanation = "Chrome executable resolution failed. Proposing Microsoft Edge as alternative browser."
                    logger.info(f"REFLECTION proposal: {explanation}")
                    return ReflectionResult(
                        failure_reason="Chrome executable not found or failed to start.",
                        root_cause="executable_not_found",
                        expected_state=expected_state,
                        actual_state=actual_state,
                        suggested_action="launch",
                        suggested_tool="application_tool",
                        suggested_args={"action": "launch", "app_name": "edge"},
                        should_retry=True,
                        explanation=explanation,
                    )
                else:
                    return ReflectionResult(
                        failure_reason="Both Chrome and Edge failed to launch.",
                        root_cause="no_available_browser",
                        expected_state=expected_state,
                        actual_state=actual_state,
                        should_retry=False,
                        explanation="Unable to launch Chrome or Edge browser. Stopping safely.",
                    )

            if app in ("notepad", "calc", "calculator", "paint", "code"):
                return ReflectionResult(
                    failure_reason=f"Application '{app}' could not be launched.",
                    root_cause="app_unavailable",
                    expected_state=expected_state,
                    actual_state=actual_state,
                    should_retry=False,
                    explanation=f"Application '{app}' is not accessible on this system.",
                )

        # 2. Browser Navigation / Page Retrieval Failure
        if tool_name == "browser_tool":
            b_action = args_dict.get("action", "")
            url = args_dict.get("url", "")
            expected_state = f"Browser page loaded at {url}"
            actual_state = f"Browser operation '{b_action}' failed: {err_msg}"

            if "timeout" in err_lower or "unreachable" in err_lower or "connection" in err_lower:
                # If http:// was used, try https:// or vice versa
                if url.startswith("http://"):
                    new_url = url.replace("http://", "https://", 1)
                    return ReflectionResult(
                        failure_reason="Browser connection timed out.",
                        root_cause="network_timeout",
                        expected_state=expected_state,
                        actual_state=actual_state,
                        suggested_action=b_action,
                        suggested_tool="browser_tool",
                        suggested_args={"action": b_action, "url": new_url},
                        should_retry=True,
                        explanation=f"Connection timed out on HTTP. Retrying with HTTPS: {new_url}",
                    )
                return ReflectionResult(
                    failure_reason="Target website is unreachable or timed out.",
                    root_cause="network_unreachable",
                    expected_state=expected_state,
                    actual_state=actual_state,
                    should_retry=False,
                    explanation=f"Website {url} could not be reached. Verify network connectivity.",
                )

        # 3. MCP Tool Failure (MCP server disconnected, missing, or tool error)
        if tool_name.startswith("mcp_"):
            expected_state = f"MCP tool '{tool_name}' successfully executed on remote server"
            actual_state = f"MCP tool failed: {err_msg}"

            # Check if an alternative native tool exists
            native_tool = self._find_native_alternative(tool_name, args_dict)
            if native_tool:
                alt_tool, alt_args = native_tool
                explanation = f"MCP tool '{tool_name}' failed. Falling back to native tool '{alt_tool}'."
                logger.info(f"REFLECTION proposal: {explanation}")
                return ReflectionResult(
                    failure_reason=f"MCP tool '{tool_name}' encountered execution error.",
                    root_cause="mcp_failure",
                    expected_state=expected_state,
                    actual_state=actual_state,
                    suggested_action=alt_args.get("action", "execute"),
                    suggested_tool=alt_tool,
                    suggested_args=alt_args,
                    should_retry=True,
                    explanation=explanation,
                )
            else:
                return ReflectionResult(
                    failure_reason=f"MCP tool '{tool_name}' failed with no native fallback.",
                    root_cause="mcp_unavailable",
                    expected_state=expected_state,
                    actual_state=actual_state,
                    should_retry=False,
                    explanation=f"MCP service unavailable: {err_msg}",
                )

        # 4. File Tool Failure (e.g. file search pattern yielded 0 results or file not found)
        if tool_name == "file_tool":
            f_action = args_dict.get("action", "")
            expected_state = f"File operation '{f_action}' successful"
            actual_state = f"File operation failed: {err_msg}"

            if f_action == "search_files":
                pattern = args_dict.get("pattern", "")
                # If specific pattern failed, try broader wildcard pattern once
                if pattern != "*" and pattern != "*.*":
                    explanation = f"File search for '{pattern}' found nothing. Trying broad search '*'."
                    return ReflectionResult(
                        failure_reason=f"Pattern '{pattern}' matched no files.",
                        root_cause="pattern_no_match",
                        expected_state=expected_state,
                        actual_state=actual_state,
                        suggested_action="search_files",
                        suggested_tool="file_tool",
                        suggested_args={"action": "search_files", "pattern": "*"},
                        should_retry=True,
                        explanation=explanation,
                    )

        # 5. Generic / Unhandled Failure
        return ReflectionResult(
            failure_reason=err_msg,
            root_cause="unhandled_failure",
            expected_state=expected or "Successful verified execution",
            actual_state=f"Operation failed with: {err_msg}",
            should_retry=False,
            explanation=f"Action '{action_name}' failed. No automated recovery strategy available.",
        )

    def _find_native_alternative(
        self,
        mcp_tool_name: str,
        args: Dict[str, Any],
    ) -> Optional[Tuple[str, Dict[str, Any]]]:
        """Finds a native DAKU tool fallback for a failing MCP tool."""
        mcp_lower = mcp_tool_name.lower()
        if "browser" in mcp_lower or "navigate" in mcp_lower or "devtools" in mcp_lower:
            return "browser_tool", {"action": args.get("action", "navigate"), "url": args.get("url", "https://www.google.com")}
        if "file" in mcp_lower or "directory" in mcp_lower:
            return "file_tool", {"action": "list_dir"}
        if "system" in mcp_lower or "metric" in mcp_lower or "ram" in mcp_lower:
            return "system_tool", {"query": "ram"}
        return None
